"""Derive the three development-training variants from a verified A YAML.

The source A must be generated by the unchanged P3 protocol using its historical
base. This tool does not infer missing historical hyperparameters.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from utils.config import load_config_mapping

VARIANTS = {"base_clean": "none", "c0_sdm": "sdm", "c0_ce": "ce"}


def derive_configs(source, dev_split_file="splits/dev_190.json", deg_lambda=1.0,
                   deg_rng_seed=None, deg_branch_prob=1.0):
    required = ("sampler", "num_instance", "lrscheduler", "warmup_epochs",
                "img_size", "temperature", "img_aug", "MLM", "loss_names",
                "batch_size", "num_epoch", "lr", "optimizer", "dataset_name",
                "use_rgbt_add_fusion")
    missing = [key for key in required if key not in source]
    if missing:
        raise ValueError("Historical A config is incomplete: " + ", ".join(missing))
    if not math.isfinite(float(deg_lambda)) or float(deg_lambda) < 0:
        raise ValueError("deg_lambda must be finite and nonnegative")
    if not 0 <= float(deg_branch_prob) <= 1:
        raise ValueError("deg_branch_prob must be in [0,1]")
    locked = {"loss_names": "sdm+mlm+id", "batch_size": 64, "num_epoch": 60,
              "lr": 1e-5, "optimizer": "Adam", "dataset_name": "RGBT-PEDES",
              "MLM": True}
    for key, value in locked.items():
        if source[key] != value:
            raise ValueError(f"A.{key} must be {value!r}; got {source[key]!r}")
    if source["sampler"] != "random":
        raise ValueError("RGB-T five-tuples currently require sampler=random; "
                         "identity is incompatible. Verify historical A before proceeding.")
    # Require the vanilla, separable additive A path rather than silently
    # disabling inherited auxiliary training methods.
    # Historical A retains these two variance switches even with use_mum=False;
    # preserve their source values. Reject all other enabled optional `use_*`
    # features, including future parser additions.
    required_false = {"mdrc_enable", "mraf_enabled"} | {
        key for key in source if key.startswith("use_") and key not in (
            "use_rgbt_add_fusion", "use_batch_uncertainty", "use_id_uncertainty"
        )
    }
    bad = [key for key in required_false if bool(source.get(key, False))]
    if bad:
        raise ValueError("Expected additive A without auxiliary modules: " + ", ".join(bad))
    if not source["use_rgbt_add_fusion"]:
        raise ValueError("A requires use_rgbt_add_fusion=true")
    if source.get("degrade_aug_mode", "none") != "none":
        raise ValueError("A requires degrade_aug_mode=none")
    if float(source.get("mraf_rel_lambda", 0.0)) != 0.0:
        raise ValueError("A requires mraf_rel_lambda=0")
    common = dict(source)
    common.update(training=True, use_rgbt_add_fusion=True,
                  mdrc_enable=False, mraf_enabled=False, mraf_rel_lambda=0.0,
                  degrade_aug_mode="none", dev_split_file=dev_split_file,
                  val_dataset="val", deg_lambda=float(deg_lambda),
                  deg_rng_seed=deg_rng_seed, deg_branch_prob=float(deg_branch_prob),
                  smoke_steps=0)
    return {name: dict(common, deg_retrieval_loss=loss)
            for name, loss in VARIANTS.items()}


def write_configs(configs, output_dir, source_path):
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    targets = [output_dir / f"{name}.yaml" for name in configs]
    manifest = output_dir / "config_derivation.json"
    if any(path.exists() for path in targets + [manifest]):
        raise FileExistsError("Refusing to overwrite derived configs; choose a new output_dir")
    for name, config in configs.items():
        # SafeDumper emits lists for historical tuple-valued image dimensions.
        serializable = {key: list(value) if isinstance(value, tuple) else value
                        for key, value in config.items()}
        (output_dir / f"{name}.yaml").write_text(
            yaml.safe_dump(serializable, allow_unicode=True, sort_keys=True), encoding="utf-8")
    manifest.write_text(json.dumps({"source_a_config": str(Path(source_path).resolve()),
                                   "variants": VARIANTS,
                                   "split_change": "official full train -> development train_reduced",
                                   "only_c0_training_difference": "deg_retrieval_loss"},
                                  indent=2, ensure_ascii=False), encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--a-config", required=True)
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--dev_split_file", default="splits/dev_190.json")
    parser.add_argument("--deg_lambda", type=float, default=1.0)
    parser.add_argument("--deg_rng_seed", type=int)
    parser.add_argument("--deg_branch_prob", type=float, default=1.0)
    args = parser.parse_args(argv)
    if args.deg_lambda < 0 or not 0 <= args.deg_branch_prob <= 1:
        parser.error("deg_lambda must be nonnegative and deg_branch_prob in [0,1]")
    configs = derive_configs(load_config_mapping(args.a_config), args.dev_split_file,
                             args.deg_lambda, args.deg_rng_seed, args.deg_branch_prob)
    write_configs(configs, args.output_dir, args.a_config)
    print(f"Wrote {', '.join(configs)} to {args.output_dir}")


if __name__ == "__main__":
    main()
